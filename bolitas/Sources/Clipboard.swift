// Bolitas — historial del portapapeles (al estilo CopyClip).
// Guarda lo último que copias (texto y enlaces) y te deja fijar lo que copias a menudo.
// Lo copiado desde gestores de contraseñas (marcado como oculto o temporal) NO se guarda nunca.
// Se cuelga en el tendedero del tejado del club y también aparece en el menú de la bolita.

import AppKit

struct ClipItem: Codable, Equatable {
    var id: String = UUID().uuidString
    var text: String
    var pinned: Bool = false
    var date: Date = Date()

    var preview: String {
        let one = text.replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
        return one.count > 60 ? String(one.prefix(59)) + "…" : one
    }
}

final class ClipStore {
    static let shared = ClipStore()
    private(set) var items: [ClipItem] = []
    var onChange: (() -> Void)?
    private let pb = NSPasteboard.general
    private var lastCount: Int
    private let maxRecent = 40
    private let file: URL
    /// El último que has vuelto a copiar desde Bolitas (para el «¡copiado!»).
    private(set) var lastCopied: (id: String, at: Date)?

    private init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Bolitas", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        file = dir.appendingPathComponent("portapapeles.json")
        lastCount = NSPasteboard.general.changeCount
        if let d = try? Data(contentsOf: file), let arr = try? JSONDecoder().decode([ClipItem].self, from: d) { items = arr }
    }

    /// Pinned primero (en el orden en que los fijaste) y después lo más reciente.
    var ordered: [ClipItem] { items.filter { $0.pinned } + items.filter { !$0.pinned } }

    private func save() {
        if let d = try? JSONEncoder().encode(items) { try? d.write(to: file, options: .atomic) }
        onChange?()
    }

    /// Se llama a menudo: mira si has copiado algo nuevo.
    func poll() {
        let cc = pb.changeCount
        guard cc != lastCount else { return }
        lastCount = cc
        let types = Set((pb.types ?? []).map { $0.rawValue })
        // Contraseñas y cosas efímeras: fuera.
        let secret = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                      "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]
        if secret.contains(where: { types.contains($0) }) { return }
        guard let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.count < 20000 else { return }
        if let i = items.firstIndex(where: { $0.text == s }) {
            // Ya estaba: sube arriba (si no está fijado).
            var it = items.remove(at: i); it.date = Date(); items.insert(it, at: 0)
        } else {
            items.insert(ClipItem(text: s), at: 0)
        }
        // Límite de recientes (los fijados no cuentan)
        var unp = 0
        items.removeAll { it in
            if it.pinned { return false }
            unp += 1
            return unp > maxRecent
        }
        save()
    }

    func copy(_ it: ClipItem) {
        pb.clearContents()
        pb.setString(it.text, forType: .string)
        lastCount = pb.changeCount
        lastCopied = (it.id, Date())
        onChange?()
    }
    func togglePin(_ id: String) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle(); save()
    }
    func remove(_ id: String) { items.removeAll { $0.id == id }; save() }
    func clearUnpinned() { items.removeAll { !$0.pinned }; save() }
}
